/// Kissat's scaling functions for limits (`kimits.c`).
pub fn logn(count: u64) -> f64 {
    ((count + 9) as f64).log10()
}

pub fn nlogpown(count: u64, exponent: u32) -> f64 {
    count as f64 * logn(count).powi(exponent as i32)
}
